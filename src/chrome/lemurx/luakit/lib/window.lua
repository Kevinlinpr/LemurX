local function make_bar_side()
    local side = { layout = widget{ type = "hbox" }, ebox = widget{ type = "eventbox" } }
    side.ebox.child = side.layout
    return side
end

local function make_tablist(w)
    if not (lousy.widget and lousy.widget.tablist) then return nil end
    local ok, tl = pcall(lousy.widget.tablist, w, { orientation = "horizontal", notebook = w.tabs })
    if not ok or type(tl) ~= "table" then
        ok, tl = pcall(lousy.widget.tablist, w.tabs, "horizontal")
    end
    if ok and type(tl) == "table" and tl.widget then return tl end
    msg.verbose("window: tablist widget unavailable (%s)", tostring(tl))
    return nil
end

local function make_menu(w)
    if not (lousy.widget and lousy.widget.menu) then return nil end
    local ok, m = pcall(lousy.widget.menu, w)
    if ok and type(m) == "table" and m.widget then return m end
    msg.verbose("window: menu widget unavailable (%s)", tostring(m))
    return nil
end

function _M.build(w)
    local th = theme()
    w.win = widget{ type = "window" }
    w.layout = widget{ type = "vbox" }
    w.win.child = w.layout

    -- 标签栏 + 页面区域（paned 让 vertical_tabs 之类的模块能把标签栏挪到左侧）
    w.tabs = widget{ type = "notebook" }
    w.tabs.show_tabs = false
    w.tabs.show_border = false
    w.paned = widget{ type = "hpaned" }
    w.paned:pack2(w.tabs, { resize = true, shrink = true })

    w.tablist = make_tablist(w)
    if w.tablist then
        w.layout:pack(w.tablist.widget)
        if w.tablist.add_signal then
            w.tablist:add_signal("tab-clicked", function(_, idx, mods, but)
                if but == 2 then
                    local view = w.tabs:atindex(idx)
                    if view then w:close_tab(view) end
                else
                    w.tabs:switch(idx)
                end
                return true
            end)
        end
    end
    w.layout:pack(w.paned, { expand = true, fill = true })

    -- 菜单（补全、undolist、tabhistory 等模式共用）
    w.menu = make_menu(w)
    if w.menu then
        w.layout:pack(w.menu.widget)
        if w.menu.hide then w.menu:hide() end
    end

    -- 状态栏
    w.sbar = { layout = widget{ type = "hbox" }, ebox = widget{ type = "eventbox" }, hidden = false }
    w.sbar.l = make_bar_side()
    w.sbar.r = make_bar_side()
    w.sbar.layout:pack(w.sbar.l.ebox, { expand = true, fill = true })
    w.sbar.layout:pack(w.sbar.r.ebox)
    w.sbar.ebox.child = w.sbar.layout
    w.sbar.ebox.bg = th.sbar_bg
    w.layout:pack(w.sbar.ebox)

    -- 输入栏
    w.ibar = {
        layout = widget{ type = "hbox" },
        ebox = widget{ type = "eventbox" },
        prompt = widget{ type = "label" },
        input = widget{ type = "entry" },
    }
    w.ibar.prompt.font = th.ibar_font
    w.ibar.input.font = th.ibar_font
    w.ibar.input.show_frame = false
    w.ibar.layout:pack(w.ibar.prompt)
    w.ibar.layout:pack(w.ibar.input, { expand = true, fill = true })
    w.ibar.ebox.child = w.ibar.layout
    w.ibar.ebox.bg = th.ibar_bg
    w.layout:pack(w.ibar.ebox)
    w.ibar.prompt:hide()
    w.ibar.input:hide()

    w.buffer = nil
    w.binds = {}
    w.closed_tabs = w.closed_tabs or {}

    _M.emit_signal("build", w)

    -- rc.lua 没有自己往状态栏塞控件时，放一套默认的
    for side, names in pairs(_M.default_sbar_widgets) do
        local bar = w.sbar[side]
        if bar and #bar.layout.children == 0 and lousy.widget then
            for _, name in ipairs(names) do
                local factory = lousy.widget[name]
                if type(factory) == "function" or (type(factory) == "table" and getmetatable(factory)) then
                    local ok, wd = pcall(factory, w)
                    if ok and is_widget(wd) then
                        bar.layout:pack(wd)
                        bar[name] = wd
                    elseif ok and type(wd) == "table" and is_widget(wd.widget) then
                        bar.layout:pack(wd.widget)
                        bar[name] = wd.widget
                    else
                        msg.verbose("window: statusbar widget %s unavailable: %s", name, tostring(wd))
                    end
                end
            end
        end
    end
end

