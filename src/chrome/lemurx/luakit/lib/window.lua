-- 窗口表的元表：先查 window.methods，再依次问 window.indexes 里的索引函数
local window_mt = {
    __index = function(w, k)
        local m = methods[k]
        if m ~= nil then return m end
        for _, fn in ipairs(_M.indexes) do
            local v = fn(w, k)
            if v ~= nil then return v end
        end
        return nil
    end,
}

-- ---------------------------------------------------------------------------
-- 查找
-- ---------------------------------------------------------------------------
function _M.ancestor(widget)
    if not is_widget(widget) then return nil end
    local cur, guard = widget, 0
    while cur and guard < 64 do
        if cur.type == "window" then return _M.bywidget[cur] end
        local ok, parent = pcall(function() return cur.parent end)
        if not ok then break end
        cur = parent
        guard = guard + 1
    end
    -- 兜底：按 notebook 成员关系找
    if widget.type == "webview" then
        for _, w in pairs(_M.bywidget) do
            if w.tabs and w.tabs.is_alive and w.tabs:indexof(widget) then return w end
        end
    end
    return nil
end

function _M.current()
    local la = _M.last_active
    if la and la.win and la.win.is_alive then return la end
    for _, win in ipairs(luakit.windows) do
        local w = _M.bywidget[win]
        if w then return w end
    end
    for _, w in pairs(_M.bywidget) do return w end
    return nil
end

