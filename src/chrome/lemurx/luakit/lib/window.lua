methods.get_current = function(w) return w.view end
methods.tab_count = function(w) return w.tabs:count() end
methods.update_buf = function() end          -- lousy.widget.buf 会覆盖
methods.set_binds = function(w, binds) w.binds = binds or {} end

methods.update_binds = function(w, mode_name)
    local modes = modes_mod()
    if not (modes and modes.get_mode) then w.binds = {} return end
    local m = modes.get_mode(mode_name or w.mode or "normal")
    local out = {}
    for _, b in ipairs(m and m.binds or {}) do out[#out + 1] = b end
    if not (m and m.passthrough) then
        local all = modes.get_mode("all")
        for _, b in ipairs(all and all.binds or {}) do out[#out + 1] = b end
    end
    w.binds = out
end

-- 默认模式实现（modes.lua 会替换成完整版）
methods.set_mode = function(w, name, ...)
    name = name or "normal"
    local old = w.mode
    w.mode = name
    w:update_binds(name)
    w:emit_signal("mode-changed", name, ...)
    if old ~= name then w:emit_signal("mode-entered", name) end
end
methods.is_mode = function(w, name) return w.mode == name end

-- 计数前缀 + 缓冲区 + lousy.bind.hit
methods.hit = function(w, mods, key, opts)
    opts = opts or {}
    local m = current_mode_table(w)
    local enable_buffer = opts.enable_buffer
    if enable_buffer == nil then enable_buffer = (m and m.enable_buffer) or false end
    local buffer = opts.buffer or w.buffer or ""
    local count, rest = buffer:match("^(%d+)(.*)$")
    local plain = (#mods == 0)

    if enable_buffer and plain and key:match("^%d$") and
       ((buffer == "" and key ~= "0") or (count and rest == "")) then
        w.buffer = buffer .. key
        w:update_buf()
        return true
    end

    local args = join(opts, { enable_buffer = enable_buffer, buffer = count and rest or buffer })
    if count then args.count = tonumber(count) end
    local caught, newbuf = lousy.bind.hit(w, w.binds or {}, mods, key, args)
    newbuf = newbuf or ""
    if not caught then newbuf = "" end
    if caught and newbuf ~= "" and count then newbuf = count .. newbuf end
    w.buffer = (newbuf ~= "") and newbuf or nil
    w:update_buf()
    return caught and true or false
end

methods.match_cmd = function(w, text, opts)
    local modes = modes_mod()
    local binds = {}
    if modes and modes.get_mode then
        local cm = modes.get_mode("command")
        binds = cm and cm.binds or {}
    end
    return lousy.bind.match_cmd(w, binds, text, opts or {})
end

methods.run_cmd = function(w, text, opts)
    text = tostring(text or "")
    text = text:gsub("^%s*:", ""):gsub("^%s+", ""):gsub("%s+$", "")
    if text == "" then return false end
    w:emit_signal("run-cmd", text)
    local name, rest = text:match("^(%S+)(.*)$")
    local o = join(opts or {}, {})
    if name:sub(-1) == "!" then
        o.bang = true
        text = name:sub(1, -2) .. rest
        name = name:sub(1, -2)
    end
    local ok, matched = xpcall(function() return w:match_cmd(text, o) end, debug.traceback)
    if not ok then
        msg.error("command %q failed: %s", name, tostring(matched))
        w:error(("command %s failed: %s"):format(name, tostring(matched):match("^[^\n]*")))
        return false
    end
    if not matched then
        w:error(("no such command: %s"):format(name))
        return false
    end
    return true
end

methods.enter_cmd = function(w, cmd, opts)
    opts = opts or {}
    w:set_mode("command")
    w:set_input(cmd or ":", opts)
end

-- 输入栏
methods.set_prompt = function(w, text, opts)
    opts = opts or {}
    local p = w.ibar.prompt
    w.ibar.prompt_text = text
    if text == nil or text == "" then
        p.text = ""
        p:hide()
        return
    end
    local th = theme()
    if opts.fg then p.fg = opts.fg end
    if opts.bg then p.bg = opts.bg; w.ibar.ebox.bg = opts.bg end
    if not opts.markup then text = escape(text) end
    p.text = text
    p:show()
end

methods.set_input = function(w, text, opts)
    opts = opts or {}
    local i = w.ibar.input
    if text == nil or (text == "" and not opts.show) then
        i.text = ""
        i:hide()
        return
    end
    i:show()
    if opts.fg then i.fg = opts.fg end
    if opts.bg then i.bg = opts.bg end
    i.text = text
    local pos = opts.pos
    if pos == nil or pos < 0 then pos = utf8.len(text) or #text end
    i.position = pos
    i:focus()
end

methods.set_ibar_theme = function(w, name)
    local th = theme()
    local fg, bg = th.ibar_fg, th.ibar_bg
    if name then
        fg = th[name .. "_fg"] or fg
        bg = th[name .. "_bg"] or bg
    end
    w.ibar.ebox.bg = bg
    w.ibar.prompt.fg = fg
    w.ibar.prompt.bg = bg
    w.ibar.input.fg = fg
    w.ibar.input.bg = bg
end

local function message(level, w, text, set_mode)
    text = tostring(text)
    if set_mode ~= false then w:set_mode() end
    local th = theme()
    w:set_prompt(text, { fg = th[level .. "_fg"], bg = th[level .. "_bg"] })
    w.ibar.last_message = { level = level, text = text }
end
methods.notify = function(w, text, set_mode) message("notif", w, text, set_mode) msg.info("%s", tostring(text)) end
methods.warning = function(w, text, set_mode) message("warning", w, text, set_mode) msg.warn("%s", tostring(text)) end
methods.error = function(w, text, set_mode) message("error", w, text, set_mode) msg.error("%s", tostring(text)) end

