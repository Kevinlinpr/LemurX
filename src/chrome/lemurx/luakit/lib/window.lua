local function current_mode_table(w)
    local modes = modes_mod()
    if modes and modes.get_mode then return modes.get_mode(w.mode or "normal") end
    return nil
end

local function wire(w)
    -- 按键：window 控件先拿到，吃掉则返回 true
    w.win:add_signal("key-press", function(_, mods, key, synthetic)
        if synthetic and not get_setting("window.act_on_synthetic_keys", false) then return end
        _M.last_active = w
        if w:emit_signal("key-press", mods, key) == true then return true end
        return w:hit(mods, key)
    end)

    w.win:add_signal("delete-event", function()
        w:close_win()
        return true
    end)

    w.win:add_signal("destroy", function()
        _M.bywidget[w.win] = nil
        if _M.last_active == w then _M.last_active = nil end
        w:emit_signal("destroy")
    end)

    w.win:add_signal("focus", function() _M.last_active = w end)

    -- 标签切换
    w.tabs:add_signal("switch-page", function(_, view, idx)
        local prev = w.view
        w.view = view
        if w.built and w.mode and w.mode ~= "normal" and w.mode ~= "insert" then w:set_mode() end
        w:update_win_title()
        if view and view.is_alive then pcall(view.emit_signal, view, "switched-page") end
        w:emit_signal("switched-page", view, prev)
    end)
    w.tabs:add_signal("page-added", function() w:emit_signal("tab-count-changed") end)
    w.tabs:add_signal("page-removed", function(_, view)
        if w.view == view then w.view = nil end
        w:emit_signal("tab-count-changed")
    end)
    w.tabs:add_signal("page-reordered", function(_, view, idx) w:emit_signal("tab-reordered", view, idx) end)

    -- 输入栏：模式表里的 changed / activate 处理器
    w.ibar.input:add_signal("changed", function()
        local m = current_mode_table(w)
        if m and m.changed then m.changed(w, w.ibar.input.text or "") end
    end)
    w.ibar.input:add_signal("activate", function()
        local m = current_mode_table(w)
        if m and m.activate then m.activate(w, w.ibar.input.text or "") end
    end)
end

