-- 标题
methods.get_tab_title = function(w, view)
    view = view or w.view
    if not (view and view.is_alive) then return "" end
    local title = view.title
    if title == nil or title == "" then title = view.uri end
    if title == nil or title == "" or title == "about:blank" then title = "(no title)" end
    return title
end

methods.update_win_title = function(w)
    if not (w.win and w.win.is_alive) then return end
    local view = w.view
    local title = "LemurX"
    if view and view.is_alive then
        title = w:get_tab_title(view)
        pcall(function() w.tabs:set_title(view, title) end)
    end
    local max = tonumber(get_setting("window.max_title_len", 80)) or 80
    if utf8.len(title) and utf8.len(title) > max then
        title = title:sub(1, utf8.offset(title, max + 1) - 1) .. "…"
    end
    w.win.title = title .. " — luakit"
end

-- 标签管理
methods.new_tab = function(w, arg, opts)
    if type(opts) == "boolean" then opts = { switch = opts } end
    opts = opts or {}
    local switch = opts.switch ~= false
    local view
    if is_view(arg) then
        view = arg
        local owner = _M.ancestor(view)
        if owner and owner ~= w then owner:detach_tab(view) end
    else
        view = webview_mod().new({ private = opts.private or w.private or false })
    end

    local order = opts.order
    local taborder = taborder_mod()
    if not order and taborder then
        order = switch and taborder.default or taborder.default_bg
    end
    local idx = -1
    if type(order) == "function" then
        local ok, i = pcall(order, w, view)
        if ok and type(i) == "number" then idx = i end
    end
    local count = w.tabs:count()
    if idx < 1 or idx > count + 1 then idx = count + 1 end
    local pos = w.tabs:insert(idx, view) or idx
    w:emit_signal("attach-tab", view)
    w:emit_signal("new-tab", view)
    if switch then w.tabs:switch(pos) end
    if not is_view(arg) then
        local target = arg
        if target == nil or target == "" then target = get_setting("window.new_tab_page", "about:blank") end
        webview_mod().set_location(view, target)
    end
    if w.tabs:count() == 1 and not w.view then w.tabs:switch(1) end
    return view
end

methods.attach_tab = function(w, view, opts) return w:new_tab(view, opts) end

methods.detach_tab = function(w, view)
    view = view or w.view
    if not is_view(view) then return end
    local idx = w.tabs:indexof(view)
    if not idx then return end
    w:emit_signal("detach-tab", view)
    w.tabs:remove(view)
    if w.view == view then w.view = nil end
    local count = w.tabs:count()
    if count > 0 then
        w.tabs:switch(math.min(idx, count))
    elseif w.built then
        if _M.close_win_when_empty then w:close_win(true) end
    end
    return view
end

methods.close_tab = function(w, view, blank_last)
    view = view or w.view
    if not is_view(view) then return end
    local idx = w.tabs:indexof(view)
    if not idx then return end
    local last = (w.tabs:count() == 1)
    w:emit_signal("close-tab", view)
    if last then
        local close_win = get_setting("window.close_with_last_tab", false) and not blank_last
        if close_win then
            w.closing_last_tab = true
        else
            w:new_tab(get_setting("window.new_tab_page", "about:blank"), { switch = true, order = function() return 1 end })
            idx = w.tabs:indexof(view) or idx
        end
    end
    w:emit_signal("detach-tab", view)
    w.tabs:remove(view)
    if w.view == view then w.view = nil end
    pcall(view.destroy, view)
    local count = w.tabs:count()
    if count > 0 then
        w.tabs:switch(math.min(idx, count))
    end
    w:emit_signal("tab-count-changed")
    if w.closing_last_tab then
        w.closing_last_tab = nil
        w:close_win()
    end
end

methods.each_tab = function(w, fn)
    for i = 1, w.tabs:count() do
        local v = w.tabs:atindex(i)
        if v then fn(v, i) end
    end
end

methods.goto_tab = function(w, n)
    local count = w.tabs:count()
    if count == 0 then return end
    n = tonumber(n) or 1
    if n < 0 then n = count + n + 1 end
    if n < 1 then n = 1 end
    if n > count then n = count end
    w.tabs:switch(n)
end

methods.next_tab = function(w, n)
    local count = w.tabs:count()
    if count == 0 then return end
    n = tonumber(n) or 1
    w.tabs:switch(((w.tabs:current() - 1 + n) % count) + 1)
end

methods.prev_tab = function(w, n)
    local count = w.tabs:count()
    if count == 0 then return end
    n = tonumber(n) or 1
    w.tabs:switch(((w.tabs:current() - 1 - n) % count) + 1)
end

methods.move_tab = function(w, offset)
    local view = w.view
    if not view then return end
    local count = w.tabs:count()
    local idx = w.tabs:indexof(view) or 1
    local target = ((idx - 1 + offset) % count) + 1
    w.tabs:reorder(view, target)
end

-- 导航
methods.navigate = function(w, uri, view)
    view = view or w.view
    if is_view(view) then
        webview_mod().set_location(view, uri)
        return view
    end
    return w:new_tab(uri)
end

methods.search_open = function(w, text)
    return webview_mod().resolve_location(text)
end

methods.new_window = function(w, uri)
    local args = {}
    if uri ~= nil then args[1] = uri end
    return _M.new(args)
end

-- 关窗
methods.can_quit = function(w)
    return w:emit_signal("can-close") ~= false
end

methods.close_win = function(w, force)
    if not (w.win and w.win.is_alive) then return true end
    if not force and w:emit_signal("can-close") == false then return false end
    w:emit_signal("close")
    -- 先把页面摘掉再销毁，避免 notebook 级联时重复回调
    local views = {}
    w:each_tab(function(v) views[#views + 1] = v end)
    for _, v in ipairs(views) do
        pcall(function() w.tabs:remove(v) end)
        pcall(v.destroy, v)
    end
    w.view = nil
    w.win:destroy()
    if _M.quit_when_no_windows and #luakit.windows == 0 then
        luakit.quit()
    end
    return true
end

-- ---------------------------------------------------------------------------
-- 构造
-- ---------------------------------------------------------------------------
function _M.new(args)
    args = args or {}
    if type(args) == "string" then args = { args } end
    local w = setmetatable({ private = args.private == true }, window_mt)
    lousy.signal.setup(w)
    w.closed_tabs = {}
    w.search_state = {}
    _M.build(w)
    _M.bywidget[w.win] = w
    wire(w)
    _M.last_active = w

    _M.emit_signal("init", w)
    for k, fn in pairs(_M.init_funcs) do
        if type(fn) == "function" then
            local ok, err = xpcall(fn, debug.traceback, w)
            if not ok then msg.error("window.init_funcs[%s]: %s", tostring(k), tostring(err)) end
        end
    end

    w:set_mode()
    w.built = true

    local size = tostring(get_setting("window.new_window_size", "800x600"))
    local sw, sh = size:match("^(%d+)x(%d+)$")
    if sw and w.win.set_default_size then pcall(w.win.set_default_size, w.win, tonumber(sw), tonumber(sh)) end

    local n = 0
    for _, a in ipairs(args) do
        n = n + 1
        w:new_tab(a, { switch = (n == 1) })
    end
    if n == 0 then
        w:new_tab(get_setting("window.home_page", "about:blank"), { switch = true })
    end
    if args.current and w.tabs:count() >= args.current then w.tabs:switch(args.current) end

    w.win:show()
    w:update_win_title()
    return w
end

return _M
